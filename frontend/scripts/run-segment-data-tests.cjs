const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const Module = require("node:module");
require.extensions[".ts"] = (loadedModule, sourceFile) => {
  loadedModule._compile(ts.transpileModule(fs.readFileSync(sourceFile, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, sourceFile);
};
const filename = path.resolve(__dirname, "../src/lib/segment-data.ts");
const compiled = ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const loaded = new Module(filename, module);
loaded.filename = filename;
loaded.paths = Module._nodeModulePaths(path.dirname(filename));
loaded._compile(compiled, filename);
const { segmentChecks, segmentKp } = loaded.exports;
const pipeline = { id: "p1", pipeLengthKm: 150, routeGeometry: { type: "LineString", coordinates: [[1, 2], [2, 3]] } };
const segments = [0, 50, 100].map((start, i) => ({ id: `s${i}`, pipelineId: "p1", segmentId: `SEG-${i}`, startKp: String(start), endKp: String(start + 50), routeGeometry: pipeline.routeGeometry }));
const docs = [{ links: [{ segment: { id: "s1" } }] }];
const checks = (segment = segments[1], records = segments, docError = false) => Object.fromEntries(segmentChecks(pipeline, segment, records, docs, docError));
assert.equal(segmentKp("0"), 0);
for (const value of [undefined, "", " ", "bad", "-1", "Infinity"]) assert.equal(segmentKp(value), null);
assert.ok(Object.values(checks()).every((result) => result === "Passed"));
assert.equal(checks(segments[0])["No gap in KP range"], "Passed", "KP zero is a valid start");
assert.equal(checks(segments[1], [segments[0], segments[1], { ...segments[2], startKp: "110" }])["No gap in KP range"], "Failed");
assert.equal(checks(segments[1], [{ ...segments[0], endKp: "60" }, ...segments.slice(1)])["No overlap with adjacent segments"], "Failed");
assert.equal(checks({ ...segments[1], endKp: "50" })["KP sequence is valid"], "Failed");
assert.equal(checks({ ...segments[1], endKp: "151" })["KP sequence is valid"], "Failed");
assert.equal(checks(segments[1], [{ ...segments[0], startKp: "bad" }, ...segments.slice(1)])["No overlap with adjacent segments"], "UNKNOWN");
assert.equal(checks(segments[1], segments, true)["Source documents linked"], "UNKNOWN");
assert.equal(checks({ ...segments[1], routeGeometry: undefined })["Geometry linked to pipeline route"], "UNKNOWN");
assert.ok(Object.values(checks(null)).every((result) => result === "UNKNOWN"));
console.log("Segment data checks passed.");
